/**
 * Банк исторических фактов для урока «Объясни мне это» (бета).
 *
 * Зачем банк, а не «расскажи интересное»: модели охотно выдумывают красивые
 * истории — легенду о Гауссе и сумме 1…100 пересказывают больше чем в сотне
 * версий, а сами числа 1–100 добавили позже (B. Hayes, American Scientist, 2006).
 * Поэтому ИИ получает только факты отсюда, каждый — с источником и пометкой
 * о достоверности, а историю рассказывает, только если она про ту же идею,
 * что и урок: интересное, но не по делу мешает учиться («эффект
 * соблазнительных деталей», мета-анализ Sundararajan & Adesope, 2020).
 *
 * keys — основы слов темы: ключ подходит, если каждая его основа начинает
 * какое-нибудь слово в теме или вопросе ученика («квадратн уравнен» ловит
 * «квадратного уравнения»).
 */

