/** Основы слов: нижний регистр, «ё» → «е», только буквы и цифры. */
function words(text: string): string[] {
  return (
    text
      .toLowerCase()
      .replace(/ё/g, 'е')
      .match(/[a-zа-яіў0-9]+/g) ?? []
  )
}

/** Ключ подходит, если каждая его основа начинает какое-нибудь слово текста. */
function keyMatches(key: string, textWords: string[]): boolean {
  return key.split(' ').every((stem) => textWords.some((w) => w.startsWith(stem)))
}

/**
 * Факты для урока: самые близкие к теме и вопросу ученика. Возвращает до limit
 * фактов (лучшие по числу совпавших основ), а при равенстве — в случайном порядке,
 * чтобы на одну тему не звучала каждый раз одна и та же история.
 */
export function pickFacts(subject: string | null | undefined, text: string, limit = 2, random = Math.random): Fact[] {
  const textWords = words(text)
  if (!textWords.length) return []
  const scored = FACTS.filter((f) => !subject || (f.subjects as string[]).includes(subject))
    .map((fact) => ({
      fact,
      score: fact.keys.filter((k) => keyMatches(k, textWords)).reduce((sum, k) => sum + k.split(' ').length, 0),
      tie: random(),
    }))
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score || a.tie - b.tie)
  return scored.slice(0, limit).map((s) => s.fact)
}
