// ---------- Помощники для проверок ----------

const lower = (text) => text.toLowerCase().replaceAll('ё', 'е')
/** Есть хотя бы одна из подстрок (без учёта регистра). */
const any = (...needles) => (text) => needles.some((n) => lower(text).includes(lower(n)))
/** Нет ни одной из подстрок. */
const none = (...needles) => (text) => !any(...needles)(text)
const words = (text) => text.split(/\s+/).filter(Boolean).length
const count = (text, ch) => text.split(ch).length - 1
const asksQuestion = (text) => /\?\s*(\*|_|\)|»|")*\s*$/m.test(text.trim().split('\n').slice(-4).join('\n')) || text.trim().endsWith('?')
/**
 * Годы в ответе — только те, что модель получила из банка фактов (worker/src/ai/facts.ts).
 * Год ищем по контексту («в 1786», «1786 г.», «(1786)»), чтобы не путать с числами из задач.
 */
const YEAR = /(?:(?:^|[\s(«])(?:в|с|до|после|около|к)\s+(1\d{3}|20[0-2]\d)(?!\d))|(?:(?<!\d)(1\d{3}|20[0-2]\d)\s*(?:г\.|год|гг|-м|-х|\)))/gi
const yearsOnly = (...allowed) => (text) => [...text.matchAll(YEAR)].every((m) => allowed.includes(m[1] ?? m[2]))

