/** Все перестановки цифр ответа «выберите три верных утверждения»: порядок записи не важен. */
const anyOrder = (digits: string): string[] => {
  if (digits.length <= 1) return [digits]
  return [...digits].flatMap((d, i) => anyOrder(digits.slice(0, i) + digits.slice(i + 1)).map((rest) => d + rest))
}

