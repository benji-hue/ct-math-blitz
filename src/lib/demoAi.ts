export async function* demoAnswer(mode: AiMode, _question: string): AsyncGenerator<string> {
  const text = ANSWERS[mode] ?? ANSWERS.tutor
  const parts = text.match(/\S+\s*/g) ?? [text]
  for (const part of parts) {
    await new Promise((r) => setTimeout(r, 18))
    yield part
  }
}
